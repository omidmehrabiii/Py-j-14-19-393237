




temperature = int(input("Enter the temperature: "))

if temperature < 0:
    print("Very cold! 🥶 Wear a heavy jacket 🧥")

elif temperature <= 10:
    print("Cold weather! 🧣 Wear warm clothes 🧥")

elif temperature <= 25:
    print("Nice weather! 😊 Wear comfortable clothes 👕")

else:
    print("Hot weather! ☀️ Wear light clothes 🩳 🕶️")